/** 문단 텍스트의 **강조** 를 <b> 로 바꾼다 (내용은 전부 이 저장소가 작성한 것) */
export function emphasize(s) {
  return String(s)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/\*\*(.+?)\*\*/g, '<b>$1</b>');
}
