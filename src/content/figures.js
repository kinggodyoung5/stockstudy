/**
 * 개념 설명용 그림 (인라인 SVG)
 *
 * 실제 주가 차트가 아니라 "개념을 보여주기 위해 손으로 그린 모식도"다.
 * 실제 사례 차트는 그 아래 탐지 결과가 따로 보여주므로, 여기서는 군더더기를 빼고
 * 설명하려는 하나만 크게 드러낸다.
 *
 * 레슨의 각 문단에 fig: 'id' 를 달면 그 문단 아래에 붙는다.
 */

const W = 640;

const C = {
  up: '#e04b4b',
  down: '#2f7fe0',
  accent: '#4dd0a7',
  warn: '#f2b134',
  violet: '#a98bff',
  blue: '#5b8def',
  muted: '#8b95a9',
  line: '#333b4b',
  text: '#e4e8f1',
  dim: 'rgba(255,255,255,.06)',
};

function svg(h, body, alt = '') {
  return `<svg viewBox="0 0 ${W} ${h}" role="img" aria-label="${alt}" xmlns="http://www.w3.org/2000/svg">
<style>
  .l{fill:none;stroke-linecap:round;stroke-linejoin:round}
  .t{font:600 12.5px Pretendard,-apple-system,'Malgun Gothic',sans-serif;fill:${C.muted}}
  .ts{font:500 11.5px Pretendard,-apple-system,'Malgun Gothic',sans-serif;fill:${C.muted}}
  .tb{font:800 13px Pretendard,-apple-system,'Malgun Gothic',sans-serif;fill:${C.text}}
  .ax{stroke:${C.line};stroke-width:1}
  .dash{stroke-dasharray:5 5}
</style>
${body}</svg>`;
}

/** 꺾은선 */
const poly = (pts, stroke, w = 2, cls = '') =>
  `<polyline class="l ${cls}" points="${pts.map((p) => p[0] + ',' + p[1]).join(' ')}" stroke="${stroke}" stroke-width="${w}"/>`;

/** 텍스트 (anchor: start|middle|end) */
const txt = (x, y, s, cls = 't', anchor = 'start', color) =>
  `<text x="${x}" y="${y}" class="${cls}" text-anchor="${anchor}"${color ? ` fill="${color}"` : ''}>${s}</text>`;

/** 가로 기준선 */
const hline = (y, x1 = 40, x2 = W - 40, color = C.line, dash = true) =>
  `<line x1="${x1}" y1="${y}" x2="${x2}" y2="${y}" stroke="${color}" stroke-width="1" ${dash ? 'stroke-dasharray="5 5"' : ''}/>`;

/** 세로 안내선 */
const vline = (x, y1, y2, color = C.warn) =>
  `<line x1="${x}" y1="${y1}" x2="${x}" y2="${y2}" stroke="${color}" stroke-width="1.5" stroke-dasharray="4 4"/>`;

/** 캔들 하나 (y좌표를 직접 받는다: 값이 작을수록 화면 위 = 높은 가격) */
function candle(x, yHigh, yOpen, yClose, yLow, w = 13) {
  const bull = yClose < yOpen;
  const col = bull ? C.up : C.down;
  const top = Math.min(yOpen, yClose);
  const h = Math.max(2.5, Math.abs(yClose - yOpen));
  return `<line x1="${x}" y1="${yHigh}" x2="${x}" y2="${yLow}" stroke="${col}" stroke-width="1.6"/>
<rect x="${x - w / 2}" y="${top}" width="${w}" height="${h}" fill="${col}" rx="1"/>`;
}

/** 라벨이 달린 화살표 */
function arrow(x1, y1, x2, y2, color = C.warn) {
  return `<defs><marker id="a${Math.round(x1 + y1 + x2 + y2)}" markerWidth="7" markerHeight="7" refX="6" refY="3.5" orient="auto">
<path d="M0,0 L7,3.5 L0,7 z" fill="${color}"/></marker></defs>
<line x1="${x1}" y1="${y1}" x2="${x2}" y2="${y2}" stroke="${color}" stroke-width="1.6" marker-end="url(#a${Math.round(x1 + y1 + x2 + y2)})"/>`;
}

/** 강조 영역 */
const band = (x, y, w, h, color, opacity = 0.13) =>
  `<rect x="${x}" y="${y}" width="${w}" height="${h}" fill="${color}" opacity="${opacity}" rx="3"/>`;

